def get_food_by_id(food_id: str) -> Optional[Dict[str, Any]]:
    for food in FOOD_DATASET:
        if food["id"] == food_id:
            return food
    return None


def match_label_to_food(label: str) -> Optional[Dict[str, Any]]:
    norm = label.lower().replace("_", " ").replace("-", " ").strip()
    if not norm:
        return None
    for food in FOOD_DATASET:
        if food["name"].lower() == norm:
            return food
        for alias in food["aliases"]:
            if alias.replace("_", " ").lower() == norm:
                return food
    return None


def scale_nutrition(food: Dict[str, Any], multiplier: float = 1.0) -> Dict[str, float]:
    m = multiplier if multiplier > 0 else 1.0
    return {
        "calories": round(food["calories"] * m),
        "protein_g": round(food["protein_g"] * m, 1),
        "carbs_g": round(food["carbs_g"] * m, 1),
        "fat_g": round(food["fat_g"] * m, 1),
        "fiber_g": round(food["fiber_g"] * m, 1),
    }
